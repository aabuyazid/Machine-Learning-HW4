"""Export the prompts you typed to the AI assistant into img/ai_prompts.tex (report Section 2.1).

Reads the Claude Code session transcripts (JSON lines) of this homework, keeps only what you
typed, and writes a LaTeX fragment that report.tex pulls in with \\input.

Run:  python export_prompts.py   (re-run right before you submit: the transcript keeps growing)
Edit MAX_CHARS / MAX_LINES below if needed.
"""
import glob
import json
import os
import re
import unicodedata

PROJECT_DIR = os.path.expanduser(
    "~/.claude/projects/-Users-arkan-Documents-School-Machine-Learning-HW-4"
)
MAX_CHARS = 1500  # pasted tracebacks / code longer than this are cut; set to None to keep everything
MAX_LINES = 6  # prompts longer than this are collapsed to first+last line; set to None to keep everything

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "img", "ai_prompts.tex")

# Not typed by you: slash-command plumbing, continuation summaries, subagent notices, shell echoes,
# and the marker Claude Code writes when you press Esc.
SKIP_PREFIXES = (
    "<local-command", "<command-name", "<task-notification", "<bash-",
    "This session is being continued", "[Request interrupted",
)
ASCII_FIXES = {
    "‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "--",
    "…": "...", "→": "->", "≤": "<=", "≥": ">=", "×": "x", "−": "-",
}


def transcripts() -> list[str]:
    """Every session of this homework, oldest first (sessions are continued across files)."""
    return sorted(glob.glob(os.path.join(PROJECT_DIR, "*.jsonl")), key=os.path.getmtime)


def user_text(message: dict) -> str:
    content = message["content"]
    if isinstance(content, str):
        return content
    parts = []
    for block in content:
        if block.get("type") == "text":
            parts.append(block["text"])
        elif block.get("type") == "image":
            parts.append("[pasted image]")
    return "\n".join(parts)


def clean(text: str) -> str:
    text = re.sub(r"<system-reminder>.*?</system-reminder>", "", text, flags=re.S)
    text = re.sub(r"</?pasted_content[^>]*>", "", text)
    return text.strip()


def to_ascii(text: str) -> str:
    # listings + pdflatex cannot take arbitrary UTF-8, so fold to ASCII.
    for a, b in ASCII_FIXES.items():
        text = text.replace(a, b)
    text = unicodedata.normalize("NFKD", text)
    return text.encode("ascii", "replace").decode("ascii")


def summarize_long(text: str) -> str:
    """Collapse prompts with more than MAX_LINES lines (usually a pasted traceback/code block)
    down to the first line and, if different, the last line -- the first line is typically
    where the pasted content starts, and the last line is typically your actual question
    trailing after it."""
    lines = text.splitlines()
    if not MAX_LINES or len(lines) <= MAX_LINES:
        return text
    first, last = lines[0].rstrip(), lines[-1].rstrip()
    omitted = len(lines) - (1 if first == last else 2)
    note = f"[... {omitted} line{'s' if omitted != 1 else ''} omitted ...]"
    return first if first == last else f"{first}\n{note}\n{last}"


def collect() -> list[tuple[str, str]]:
    prompts = []
    for path in transcripts():
        with open(path) as f:
            for line in f:
                d = json.loads(line)
                if d.get("type") != "user" or d.get("isMeta"):
                    continue
                text = clean(user_text(d["message"]))
                if not text or text.startswith(SKIP_PREFIXES):
                    continue
                prompts.append((d["timestamp"][:10], text))
    return prompts


def main() -> None:
    prompts = collect()
    lines = [
        "% Generated by export_prompts.py -- do not edit by hand.",
        r"\begin{enumerate}[label=\textbf{P\arabic*.},leftmargin=2.6em,itemsep=4pt]",
    ]
    for date, text in prompts:
        text = to_ascii(summarize_long(text))
        if MAX_CHARS and len(text) > MAX_CHARS:
            text = text[:MAX_CHARS].rstrip() + f"\n[... {len(text) - MAX_CHARS} more characters omitted ...]"
        text = text.replace(r"\end{lstlisting}", r"\end{ lstlisting}")  # would close the listing early
        lines.append(rf"\item {{\footnotesize\color{{black!60}}{date}}}")
        lines.append(r"\begin{lstlisting}[style=prompt]")
        lines.append(text)
        lines.append(r"\end{lstlisting}")
    lines.append(r"\end{enumerate}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(prompts)} prompts from {len(transcripts())} transcript file(s))")


if __name__ == "__main__":
    main()
